#!/usr/bin/env bash
# Bounded offline measurement for the r24 lane OracleMissingNonrequired.
# Rebuilds the fixture, records the frozen r23 (0df800e) auditor behaviour on
# every variant, and records the plain-git object-graph facts the candidate
# implementation depends on.  No network, no clone, no transport, no
# candidate code.
set -u
OUT=/home/vgpnk/Projects/shokunin/kama-shokunin/.ufo/waves/round-24/build/out/OracleMissingNonrequired
SCRATCH=/fast/scratch/hyaku/kama-r24/OracleMissingNonrequired
BASE=0df800e896f6bce285a81e794ad4ae1d1e6c3a71
mkdir -p "$SCRATCH"
cd "$SCRATCH" || exit 1
if [ ! -f base_audit.py ]; then
  git -C "$SCRATCH" show "$BASE:tools/report-landing-audit.py" > base_audit.py || exit 1
fi
LOG="$OUT/measurements.md"
{
  echo "# Measurements - lane OracleMissingNonrequired (r24)"
  echo
  echo "Generated by \`$OUT/measure.sh\` (bounded, offline, local git only)."
  echo
  echo "## 0. Provenance"
  echo
  echo '```'
  echo "\$ git rev-parse HEAD        # scratch clone"
  git -C "$SCRATCH" rev-parse HEAD
  echo "\$ sha256sum base_audit.py   # frozen r23 auditor"
  sha256sum base_audit.py
  echo "\$ git --version; python3 --version"
  git --version; python3 --version
  echo '```'
  echo
  echo "## 1. Fixture build (premises)"
  echo
  echo '```'
  python3 "$OUT/build_fixture.py" > fixture.json 2> fixture.err
  echo "rc=$?"
  python3 - <<'PY'
import json
d = json.load(open("/fast/scratch/hyaku/kama-r24/OracleMissingNonrequired/fixture.json"))
for name, v in sorted(d.items()):
    p = v["premises"]
    print(f"{name}: missing={p['missing_object']} blob={p['missing_blob'][:12]}")
    print(f"  all-refs walk missing lines : {p['rev_list_all_missing_lines']}")
    print(f"  lane-root (master) missing   : {p['rev_list_lane_root_missing_lines']}")
    print(f"  fleet-root (HEAD) missing    : {p['rev_list_fleet_root_missing_lines']}")
    print(f"  fleet all-refs missing       : {p['rev_list_all_fleet_missing_lines']}")
    print(f"  cited commit present={p['cited_commit_present']} "
          f"peels={p['cited_commit_peels']} cutoff={p['fleet_cutoff']} "
          f"side_is_ancestor_of_master={p['side_is_ancestor_of_master']}")
PY
  echo '```'
  echo
  echo "## 2. Frozen r23 auditor (base 0df800e) on every variant"
  echo
  echo '```'
  for t in marked unmarked_twin fleet_marked selected_missing; do
    echo "\$ python3 base_audit.py --lane-repo fixture/$t/lane --fleet-repo fixture/$t/fleet --rounds 1 --no-errata --json"
    python3 base_audit.py --lane-repo "fixture/$t/lane" --fleet-repo "fixture/$t/fleet" --rounds 1 --no-errata --json > "b_$t.json" 2> "b_$t.err"
    echo "exit=$?"
    sed 's/^/  stderr: /' "b_$t.err"
    python3 - "$t" <<'PY'
import json, sys
t = sys.argv[1]
try:
    d = json.load(open(f"/fast/scratch/hyaku/kama-r24/OracleMissingNonrequired/b_{t}.json"))
except Exception as exc:
    print(f"  (no verdict document: {exc.__class__.__name__})")
else:
    s, r = d["summary"], d["results"][0]
    print("  summary:", json.dumps({k: s[k] for k in ("defects", "uncorrected", "required_commits", "post_report_commits", "reports", "status")}, sort_keys=True))
    print("  result :", json.dumps({k: r[k] for k in ("round", "cutoff", "report_committed", "round_commits", "required")}, sort_keys=True))
PY
  done
  echo '```'
  echo
  echo "## 3. Plain-git facts the candidate's closure check depends on"
  echo
  L="$SCRATCH/fixture/marked/lane"
  B=$(python3 -c "import json;print(json.load(open('$SCRATCH/fixture.json'))['marked']['missing_blob'])")
  echo '```'
  echo "\$ git -C \$L rev-list --objects --all            # default missing action"
  git -C "$L" rev-list --objects --all >/dev/null 2>/tmp/m1; echo "rc=$? ; stderr: $(head -1 /tmp/m1)"
  echo "\$ git -C \$L --no-lazy-fetch rev-list --objects --all   # default action, fetch suppressed"
  git -C "$L" --no-lazy-fetch rev-list --objects --all >/dev/null 2>/tmp/m2; echo "rc=$? ; stderr: $(head -1 /tmp/m2)"
  echo "\$ git -C \$L --no-lazy-fetch rev-list --objects --missing=print --no-object-names --all"
  git -C "$L" --no-lazy-fetch rev-list --objects --missing=print --no-object-names --all 2>/tmp/m3 | sed 's/^/  /'
  echo "rc=${PIPESTATUS[0]} ; stderr: $(head -1 /tmp/m3)"
  echo "\$ git -C \$L --no-lazy-fetch rev-list --objects --missing=print --no-object-names master   # lane evidence root"
  git -C "$L" --no-lazy-fetch rev-list --objects --missing=print --no-object-names master 2>/tmp/m4 | sed 's/^/  /'
  echo "rc=${PIPESTATUS[0]} ; stderr: $(head -1 /tmp/m4)"
  echo "\$ printf '%s\\n' \$B | git -C \$L --no-lazy-fetch cat-file --batch-check"
  printf '%s\n' "$B" | git -C "$L" --no-lazy-fetch cat-file --batch-check | sed 's/^/  /'
  echo "\$ GIT_TRACE=1 git -C \$L --no-lazy-fetch cat-file -e \$B   # lazy fetch suppressed?"
  GIT_TRACE=1 git -C "$L" --no-lazy-fetch cat-file -e "$B" 2>&1 | grep -ci "fetch\|remote" | sed 's/^/  trace fetch\/remote mentions: /'
  echo '```'
  echo
  echo "## 4. Candidate runs"
  echo
  echo "Not run: the r24 candidate does not exist at pinning time (the only"
  echo "auditor available is the frozen r23 base above)."
} > "$LOG"
echo "wrote $LOG"
