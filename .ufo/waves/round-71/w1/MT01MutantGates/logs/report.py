def fu(line):
    m = re.search(r"failed=(\d+) uncommitted=(\d+)", line)
    return f"{m.group(1)}/{m.group(2)}" if m else line

def row1(tag, rec):
    st = rec["ST"]["line"].replace("PRE_REPORT_SELFTEST ","")
    g = rec["FIX"]
    return (f"| {tag} | {rec['ST']['exit']} `{st}` | {rec['FIX']['c1-green']['exit']} `{fu(g['c1-green']['line'])}` | "
            f"{g['fx-uncommitted']['exit']} `{fu(g['fx-uncommitted']['line'])}` | {g['fx-stale']['exit']} `{fu(g['fx-stale']['line'])}` | "
            f"{g['fx-missing']['exit']} `{fu(g['fx-missing']['line'])}` | {g['fx-dirty']['exit']} `{fu(g['fx-dirty']['line'])}` | "
            f"{g['fx-crlf']['exit']} `{fu(g['fx-crlf']['line'])}` |")

def row2(tag, rec):
    bad = [v for k, v in rec["BAD"]["cases"].items() if k in "12345"]
    bt = "FAIL" if bad and all(v == "FAIL" for v in bad) else ("held" if bad and all(v == "held" for v in bad) else "mixed")
    c7 = {"held": "held", "FAIL": "FAIL"}.get(rec["LB"].get("case7"), "-")
    return (f"| {tag} | {rec['ST']['exit']} `{rec['ST']['line'].replace('BOUNDARY_SELFTEST ','')}` | "
            f"{rec['R']['exit']} `{rec['R']['line']}` | {rec['BAD']['exit']} `cases1-5 {bt}` | "
            f"{rec['HOLE']['exit']} `{rec['HOLE']['line']}` | {rec['LB']['exit']} `case7 {c7}` |")

def row3(tag, rec):
    g = rec["FIX"]
