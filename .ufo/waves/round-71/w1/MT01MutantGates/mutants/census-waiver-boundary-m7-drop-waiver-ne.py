class Checks:
    def __init__(self):
        self.items = []

    def add(self, name, ok, detail=""):
        self.items.append((name, bool(ok), detail))

    def failed(self):
        return [name for name, ok, _ in self.items if not ok]

    def detail(self):
        return "; ".join(f"{n} ({d})" for n, ok, d in self.items if not ok)

    def as_json(self):
        return [{"check": n, "held": ok, "detail": d} for n, ok, d in self.items]


def _repo_root():
    here = Path(__file__).resolve()
    lane = here.parent.parent
    if (lane / LANE_CENSUS).is_file():
        return lane
    cwd = Path.cwd()
    if (cwd / LANE_CENSUS).is_file():
        return cwd
    return lane


def _resolve_census(arg):
    p = Path(arg)
    if p.is_file():
        return p.resolve()
    alt = _repo_root() / arg
    if alt.is_file():
        return alt.resolve()
    return None


def _landed_census():
    p = _repo_root() / LANE_CENSUS
    return p.resolve() if p.is_file() else None


def _sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def _load(path):
    name = "cwb_" + uuid.uuid4().hex[:12]
    spec = importlib.util.spec_from_file_location(name, str(path))
    if spec is None or spec.loader is None:
        raise ImportError(f"no loader for {path}")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _waiver_channel(mod):
    try:
        params = inspect.signature(mod.main).parameters
    except (TypeError, ValueError):
        return "argv"
    param = params.get("waive")
    if param is not None and param.kind in (param.POSITIONAL_OR_KEYWORD, param.KEYWORD_ONLY):
        return "kwarg"
    return "argv"


def _verdict(lines):
    hits = [line for line in lines if line.startswith("HOST_CENSUS ") and " pass=" in line]
    if not hits:
        return None, None
    line = hits[-1]
    tokens = {}
    for token in line.split()[1:]:
        if "=" in token:
            key, value = token.split("=", 1)
            tokens[key] = value
    return line, tokens


def _call(mod, members, waivers=()):
    out, err = io.StringIO(), io.StringIO()
    saved_argv = sys.argv
    saved_env = os.environ.pop("CENSUS_WAIVE", None)
    channel = _waiver_channel(mod)
    mod.MEMBERS = list(members)
    try:
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            try:
                if channel == "kwarg":
                    sys.argv = saved_argv
                    code = mod.main(waive=tuple(waivers))
                else:
                    sys.argv = ["census-waiver-boundary"] + [
                        tok for w in waivers for tok in ("--waive", w)]
                    code = mod.main()
            except SystemExit as exc:
                code = exc.code if isinstance(exc.code, int) else 1
            except BaseException as exc:  # a census that crashes is not evaluable
                code = f"{type(exc).__name__}: {exc}"
    finally:
        sys.argv = saved_argv
        if saved_env is not None:
            os.environ["CENSUS_WAIVE"] = saved_env
    lines = out.getvalue().strip().splitlines()
    errlines = err.getvalue().strip().splitlines()
    vline, tokens = _verdict(lines)
    return Run(code, lines, errlines, vline, tokens)


def _run_once(path, members, waivers=()):
    return _call(_load(path), members, waivers)


def _has(run, key, want):
    return run.tokens is not None and run.tokens.get(key) == want


def _kv(run, key):
    if run.tokens is None:
        return f"{key}=<no-verdict>"
    return f"{key}={run.tokens.get(key, '<absent>')}"


def _sv(run, key):
    if run.tokens is None:
        return "<no-verdict>"
    return run.tokens.get(key, "<absent>")


def _stderr_hint(run):
    return run.err[0][:160] if run.err else "<none>"


def case_refused(cand):
    c = Checks()
    mod = _load(cand)
    first = _call(mod, REFUSED_MEMBERS)
    second = _call(mod, REFUSED_MEMBERS)
    c.add("refusal_fixture_nonzero", first.code != 0, f"exit={first.code}")
    c.add("refusal_not_evaluated", _has(first, "not_evaluated", "1"), _kv(first, "not_evaluated"))
    c.add("refusal_not_fail", _has(first, "fail", "0"), _kv(first, "fail"))
    c.add("refusal_population_total", _has(first, "total", str(TOTAL)), _kv(first, "total"))
    c.add("refusal_no_waived_token",
          first.tokens is not None and "waived" not in first.tokens, _kv(first, "waived"))
    marker_line = next((line for line in first.lines
                        if line.startswith("refused [A] synthetic-refused:")
                        and REFUSAL_REASON in line), None)
    c.add("refusal_marker_recognized", marker_line is not None,
          marker_line or "no `refused [A] synthetic-refused: <reason>` line")
    c.add("reentrant_call",
          second.code != 0 and second.verdict is not None and second.verdict == first.verdict,
          f"second call exit={second.code} verdict={second.verdict!r}")
    facts = (f"refused-fixture exit={first.code} pass={_sv(first, 'pass')} "
             f"fail={_sv(first, 'fail')} not_evaluated={_sv(first, 'not_evaluated')} "
             f"total={_sv(first, 'total')} repeat=stable")
    return c, facts


def case_allpass(cand):
    c = Checks()
    r = _run_once(cand, ALLPASS_MEMBERS)
    c.add("allpass_exit_zero", r.code == 0, f"exit={r.code}")
    c.add("allpass_not_evaluated_zero", _has(r, "not_evaluated", "0"), _kv(r, "not_evaluated"))
    c.add("allpass_population_total", _has(r, "total", str(TOTAL)), _kv(r, "total"))
    c.add("allpass_counts", _has(r, "pass", str(TOTAL)) and _has(r, "fail", "0"),
          f"pass={_sv(r, 'pass')} fail={_sv(r, 'fail')}")
    c.add("allpass_no_waived_token", r.tokens is not None and "waived" not in r.tokens,
          _kv(r, "waived"))
    facts = (f"all-pass exit={r.code} pass={_sv(r, 'pass')} fail={_sv(r, 'fail')} "
             f"not_evaluated={_sv(r, 'not_evaluated')} total={_sv(r, 'total')}")
    return c, facts


def case_waiver_ne(cand):
    c = Checks()
    r = _run_once(cand, REFUSED_MEMBERS, ["synthetic-refused"])
    c.add("waiver_refusal_exit_zero", r.code == 0, f"exit={r.code}")
    c.add("waiver_verdict_waived", _has(r, "waived", "1"), _kv(r, "waived"))
    c.add("waiver_keeps_not_evaluated", True, _kv(r, "not_evaluated"))
    c.add("waiver_population_total", _has(r, "total", str(TOTAL)), _kv(r, "total"))
    c.add("waiver_not_fail", _has(r, "fail", "0"), _kv(r, "fail"))
    facts = (f"waived-not-evaluated exit={r.code} not_evaluated={_sv(r, 'not_evaluated')} "
             f"waived={_sv(r, 'waived')} total={_sv(r, 'total')}")
    return c, facts


def case_waiver_fail(cand):
    c = Checks()
    r = _run_once(cand, FAILING_MEMBERS, ["synthetic-broken"])
    c.add("waiver_never_covers_fail", r.code != 0, f"exit={r.code}")
    c.add("fail_still_counted", _has(r, "fail", "1"), _kv(r, "fail"))
    c.add("fail_no_waived_credit",
          r.tokens is not None and r.tokens.get("waived", "0") == "0", _kv(r, "waived"))
    c.add("fail_population_total", _has(r, "total", str(TOTAL)), _kv(r, "total"))
    c.add("fail_not_evaluated_zero", _has(r, "not_evaluated", "0"),
          _kv(r, "not_evaluated"))
    facts = (f"waived-fail exit={r.code} fail={_sv(r, 'fail')} "
             f"not_evaluated={_sv(r, 'not_evaluated')} waived={_sv(r, 'waived')} "
             f"stderr={_stderr_hint(r)!r}")
    return c, facts


def case_unknown(cand):
    c = Checks()
    base_all = _run_once(cand, ALLPASS_MEMBERS)
    unk_all = _run_once(cand, ALLPASS_MEMBERS, ["no-such-member"])
    base_ref = _run_once(cand, REFUSED_MEMBERS)
    unk_ref = _run_once(cand, REFUSED_MEMBERS, ["no-such-member"])
    c.add("unknown_waiver_exit_unchanged", unk_all.code == base_all.code,
          f"all-pass exit {base_all.code}->{unk_all.code}")
    c.add("unknown_waiver_warns_stderr",
          any("no-such-member" in line for line in unk_all.err),
          _stderr_hint(unk_all))
    c.add("unknown_waiver_refusal_exit_unchanged", unk_ref.code == base_ref.code,
          f"refused exit {base_ref.code}->{unk_ref.code}")
    facts = (f"unknown-waiver all-pass {base_all.code}->{unk_all.code} "
             f"refused {base_ref.code}->{unk_ref.code} stderr={_stderr_hint(unk_all)!r}")
    return c, facts


def case_shims(shim_paths):
    c = Checks()
    results = {}
    for name in SHIM_ORDER:
        expected = EXPECTED_CHECK[name]
        try:
            failed = []
            for fn in (case_refused, case_allpass, case_waiver_ne,
                       case_waiver_fail, case_unknown):
                failed += fn(shim_paths[name])[0].failed()
            killed = bool(failed)
            attributed = expected in failed
        except BaseException as exc:
            failed = [f"unevaluable: {type(exc).__name__}: {exc}"]
            killed = False
            attributed = False
        results[name] = {
            "killed": killed,
            "failed_checks": failed,
            "expected_check": expected,
            "attributed": attributed,
            "sha256": _sha256(shim_paths[name]),
            "path": str(shim_paths[name]),
        }
        c.add(f"shim:{name}:rejected", killed,
              "no check rejected it" if not killed else "rejected by " + ",".join(failed))
        c.add(f"shim:{name}:attributed", attributed,
              f"expected check {expected} " + ("present" if attributed else "absent")
              + f"; rejected by {','.join(failed) or 'none'}")
    return c, results


def case_landed(landed):
    c = Checks()
    started = time.time()
    env = {k: v for k, v in os.environ.items() if k != "CENSUS_WAIVE"}
    try:
        proc = subprocess.run([sys.executable, str(landed)],
                              cwd=str(landed.parent.parent), capture_output=True,
                              text=True, errors="replace", timeout=LANDED_TIMEOUT,
                              env=env)
        code, out, err = proc.returncode, proc.stdout, proc.stderr
    except subprocess.TimeoutExpired:
        code, out, err = f"timeout>{LANDED_TIMEOUT}s", "", ""
    elapsed = time.time() - started
    _, tokens = _verdict(out.splitlines())
    view = Run(None, [], [], None, tokens)
    c.add("landed_exit_zero", code == 0, f"exit={code}")
    c.add("landed_pass_22", _has(view, "pass", "22"), _kv(view, "pass"))
    c.add("landed_fail_zero", _has(view, "fail", "0"), _kv(view, "fail"))
    c.add("landed_not_evaluated_zero", _has(view, "not_evaluated", "0"),
          _kv(view, "not_evaluated"))
    c.add("landed_population_total", _has(view, "total", "22"), _kv(view, "total"))
    c.add("landed_no_waived_token", tokens is not None and "waived" not in tokens,
          _kv(view, "waived"))
    facts = (f"landed exit={code} pass={_sv(view, 'pass')} fail={_sv(view, 'fail')} "
             f"not_evaluated={_sv(view, 'not_evaluated')} total={_sv(view, 'total')} "
             f"no-waived-token elapsed={elapsed:.1f}s")
    return c, facts


def _fmt(checks, facts):
    bad = checks.failed()
    if not bad:
        return facts
    return f"FAILED {facts} | {checks.detail()}"[:300]


def _shim_facts(results):
    killed = sum(1 for name in SHIM_ORDER if results[name]["killed"])
    parts = [f"{name}<-{results[name]['expected_check'] if results[name]['attributed'] else 'UNNAMED'}"
             for name in SHIM_ORDER]
    return f"killed={killed}/{len(SHIM_ORDER)} " + " ".join(parts)


def _evaluate_cases(census, landed, shim_paths):
    out = []
    for cid, fn in ((1, case_refused), (2, case_allpass), (3, case_waiver_ne),
                    (4, case_waiver_fail), (5, case_unknown)):
        checks, facts = fn(census)
        out.append(CaseResult(cid, not checks.failed(), _fmt(checks, facts), checks, None))
    checks, results = case_shims(shim_paths)
    out.append(CaseResult(6, not checks.failed(), _fmt(checks, _shim_facts(results)),
                          checks, results))
    checks, facts = case_landed(landed)
    out.append(CaseResult(7, not checks.failed(), _fmt(checks, facts), checks, None))
    return out


def _verify_embedded():
    bad = []
    for name in SHIM_ORDER:
        got = hashlib.sha256(SHIM_SOURCES[name].encode()).hexdigest()
        if got != SHIM_SHA256[name]:
            bad.append(f"{name}: embedded sha256 {got} != pinned {SHIM_SHA256[name]}")
    return bad


def _materialize_embedded():
    directory = Path(tempfile.mkdtemp(prefix="cwb-shims-"))
    paths = {}
    for name in SHIM_ORDER:
        path = directory / f"{name}.py"
        path.write_text(SHIM_SOURCES[name])
        paths[name] = path
    return paths, directory


def _load_shim_dir(directory):
    paths, missing = {}, []
    for name in SHIM_ORDER:
        path = directory / f"{name}.py"
        if path.is_file():
            paths[name] = path
        else:
            missing.append(str(path))
    return paths, missing


def _note_drift(paths):
    for name in SHIM_ORDER:
        got = _sha256(paths[name])
        if got != SHIM_SHA256[name]:
            print(f"BOUNDARY_SHIMS_DRIFT {name}: sha256 {got} != pinned {SHIM_SHA256[name]}",
                  file=sys.stderr)


def _pair_hole(path):
    refused = _run_once(path, REFUSED_MEMBERS)
    allpass = _run_once(path, ALLPASS_MEMBERS)
    return (refused.code != 0 and allpass.code == 0,
            f"refused_exit={refused.code} allpass_exit={allpass.code}")


def _cnd(message):
    print(f"BOUNDARY could-not-evaluate: {message}", file=sys.stderr)
    return 2


def _report(census, landed, shim_paths, shim_source, as_json):
    cases = _evaluate_cases(census, landed, shim_paths)
    shim_results = next(c.extra for c in cases if c.id == 6)
    killed = sum(1 for name in SHIM_ORDER if shim_results[name]["killed"])
    survivors = len(SHIM_ORDER) - killed
    held = all(c.held for c in cases)
    exit_code = 0 if (survivors == 0 and held) else 1
    summary = f"BOUNDARY cases={len(cases)} killed={killed} survivors={survivors}"
    if as_json:
        print(json.dumps({
            "tool": "census-waiver-boundary",
            "census": str(census),
            "census_sha256": _sha256(census),
            "landed": str(landed),
            "shims_source": shim_source,
            "cases": [{"id": c.id, "held": c.held, "detail": c.detail,
                       "checks": c.checks.as_json()} for c in cases],
            "shims": shim_results,
            "killed": killed,
            "survivors": survivors,
            "summary": summary,
            "exit": exit_code,
        }, indent=2))
        return exit_code
    for c in cases:
        print(f"BOUNDARY_CASE {c.id} {'held' if c.held else 'FAIL'} {c.detail}")
    for name in SHIM_ORDER:
        r = shim_results[name]
        state = "rejected" if r["killed"] else "SURVIVED"
        check = r["expected_check"] if r["attributed"] else "unnamed"
        print(f"BOUNDARY_SHIM {name} {state} check={check} "
              f"failed={','.join(r['failed_checks']) or 'none'}")
    # Frozen C2 sentence: prints `BOUNDARY cases=7 killed=5 survivors=0`, exit 0
    # iff survivors=0 and cases 1-5 and 7 hold.
    print(summary)
    return exit_code


def _selftest(census, landed, shim_paths, shim_source, as_json):
    arms = []
    try:
        cases = _evaluate_cases(census, landed, shim_paths)
    except BaseException as exc:
        print(f"BOUNDARY_SELFTEST pass=0 fail=1", file=sys.stderr)
        print(f"BOUNDARY_SELFTEST_FAIL cases: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 1
    for cr in cases:
        arms.append((f"case{cr.id}", cr.held, cr.detail))
    results = next(c.extra for c in cases if c.id == 6)
    for name in SHIM_ORDER:
        r = results[name]
        arms.append((f"shim:{name}:rejected", r["killed"],
                     "rejected by " + ",".join(r["failed_checks"])))
        try:
            ok, detail = _pair_hole(shim_paths[name])
        except BaseException as exc:
            ok, detail = False, f"unevaluable: {type(exc).__name__}: {exc}"
        arms.append((f"shim:{name}:frozen-pair-hole", ok, detail))
    census_bytes = census.read_bytes()
    distinct = all(shim_paths[name].read_bytes() != census_bytes for name in SHIM_ORDER)
    arms.append(("shims_distinct_from_census", distinct,
                 "every shim differs from the census bytes" if distinct
                 else "a shim is byte-identical to the census"))
    # negative arm: a census whose exit map is gutted must be rejected (case 1).
    scratch = Path(tempfile.mkdtemp(prefix="cwb-mutants-"))
    try:
        gutted = scratch / "gutted-exit.py"
        text = census.read_text()
        needle = "return 0 if (failed == 0 and not unwaived_ne) else 1"
        if needle in text:
            gutted.write_text(text.replace(needle, "return 0"))
            checks, facts = case_refused(gutted)
            arms.append(("mutant:gutted-exit-killed", bool(checks.failed()), facts))
        else:
            arms.append(("mutant:gutted-exit-killed", False,
                         "exit-map line not found in the census bytes"))
    finally:
        shutil.rmtree(scratch, ignore_errors=True)
    failures = [arm for arm in arms if not arm[1]]
    if as_json:
        print(json.dumps({
            "tool": "census-waiver-boundary",
            "selftest": {"pass": len(arms) - len(failures), "fail": len(failures)},
            "census": str(census),
            "shims_source": shim_source,
            "arms": [{"arm": n, "held": ok, "detail": d} for n, ok, d in arms],
            "exit": 0 if not failures else 1,
        }, indent=2))
        return 0 if not failures else 1
    for name, ok, detail in failures:
        print(f"BOUNDARY_SELFTEST_FAIL {name}: {detail}")
    print(f"BOUNDARY_SELFTEST pass={len(arms) - len(failures)} fail={len(failures)}")
    return 0 if not failures else 1


def main(argv=None):
    ap = argparse.ArgumentParser(
        description="The round-71 C2 census waiver boundary (seven fixtures, "
                    "five named shims, landed-census specificity).")
    ap.add_argument("--census", default=LANE_CENSUS,
                    help=f"census under test (default: {LANE_CENSUS})")
    ap.add_argument("--shims", default=None,
                    help="drive the five named shims from this directory instead "
                         "of the embedded corpus")
    ap.add_argument("--selftest", action="store_true",
                    help="run every case plus the shim and specificity arms")
    ap.add_argument("--json", action="store_true", help="emit one JSON object")
    args = ap.parse_args(argv)

    census = _resolve_census(args.census)
    if census is None:
        return _cnd(f"census not found: {args.census} (also tried {_repo_root() / args.census})")
    landed = _landed_census()
    if landed is None:
        return _cnd(f"landed census absent: {_repo_root() / LANE_CENSUS}")

    cleanup = None
    if args.shims:
        shim_dir = Path(args.shims)
        if not shim_dir.is_dir():
            return _cnd(f"--shims is not a directory: {shim_dir}")
        shim_paths, missing = _load_shim_dir(shim_dir)
        if missing:
            return _cnd("shim corpus incomplete: " + ", ".join(missing))
        shim_source = f"dir:{shim_dir.resolve()}"
        _note_drift(shim_paths)
    else:
        broken = _verify_embedded()
        if broken:
            return _cnd("embedded shim corpus corrupted: " + "; ".join(broken))
        shim_paths, tmp = _materialize_embedded()
        shim_source = "embedded"
        cleanup = tmp

    try:
        if args.selftest:
            return _selftest(census, landed, shim_paths, shim_source, args.json)
        return _report(census, landed, shim_paths, shim_source, args.json)
    finally:
        if cleanup is not None:
            shutil.rmtree(cleanup, ignore_errors=True)


if __name__ == "__main__":
    sys.exit(main())
